/**
 * Russian numeral agreement: 1 выпуск / 2 выпуска / 5 выпусков.
 * Teens (11–14) always take the genitive plural, hence the mod-100 guard.
 */
function plural(n: number, one: string, few: string, many: string): string {
  const h = Math.abs(n) % 100;
  if (h >= 11 && h <= 14) return many;
  const d = h % 10;
  if (d === 1) return one;
  if (d >= 2 && d <= 4) return few;
  return many;
}

