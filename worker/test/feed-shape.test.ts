import { describe, expect, it } from 'vitest';
import { isFeedDocument } from '../src/feed-shape';

const bytes = (s: string) => new TextEncoder().encode(s);

describe('isFeedDocument accepts feed roots', () => {
  it.each([
    ['rss', '<rss version="2.0"><channel></channel></rss>'],
    ['RSS in capitals', '<RSS><channel/></RSS>'],
    ['atom feed', '<feed xmlns="http://www.w3.org/2005/Atom"></feed>'],
    ['prefixed atom feed', '<atom:feed xmlns:atom="http://www.w3.org/2005/Atom"></atom:feed>'],
    ['rdf:RDF', '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"></rdf:RDF>'],
    ['a prefixed rss root', '<x:rss xmlns:x="urn:x"></x:rss>'],
    ['an xml declaration', '<?xml version="1.0" encoding="UTF-8"?>\n<rss></rss>'],
    ['a leading BOM', '\uFEFF<rss></rss>'],
    ['a BOM, declaration and whitespace', '\uFEFF  \n<?xml version="1.0"?>\n  <rss></rss>'],
    ['a comment before the root', '<!-- generated by a CMS --><rss></rss>'],
    ['a DOCTYPE before the root', '<!DOCTYPE rss PUBLIC "-//x//y" "z.dtd"><rss></rss>'],
    ['a DOCTYPE with an internal subset', '<!DOCTYPE rss [ <!ENTITY note "a > b"> ]>\n<rss></rss>'],
    ['every prologue item together', '\uFEFF<?xml version="1.0"?><!-- c --><!DOCTYPE rss><rss></rss>'],
  ])('%s', (_label, text) => {
    expect(isFeedDocument(bytes(text))).toBe(true);
  });

  it('UTF-16 with a BOM', () => {
    const text = '<?xml version="1.0"?><rss></rss>';
    const utf16 = new Uint8Array(2 + text.length * 2);
    utf16[0] = 0xff;
    utf16[1] = 0xfe;
    for (let i = 0; i < text.length; i++) {
      utf16[2 + i * 2] = text.charCodeAt(i) & 0xff;
      utf16[3 + i * 2] = text.charCodeAt(i) >> 8;
    }
    expect(isFeedDocument(utf16)).toBe(true);
  });
});

describe('isFeedDocument refuses everything else', () => {
  it.each([
    ['an HTML page', '<!doctype html><html><head></head><body>hi</body></html>'],
    ['an HTML page with a feed-like tag later', '<html><body><rss></rss></body></html>'],
    ['JSON', '{"resultCount":0,"results":[]}'],
    ['a JSON array', '[{"rss":true}]'],
    ['plain text', 'hello world'],
    ['an empty body', ''],
    ['a declaration and nothing else', '<?xml version="1.0"?>'],
    ['a root that is not a feed', '<channel><title>x</title></channel>'],
    ['an rss-like name', '<rss2><item/></rss2>'],
    ['an rdf root without the rdf prefix', '<RDF xmlns="urn:x"></RDF>'],
    ['an unterminated comment', '<!-- never closed <rss></rss>'],
    ['an unterminated declaration', '<?xml version="1.0"'],
    ['a feed root beyond the head', '<!--' + 'a'.repeat(5000) + '--><rss></rss>'],
  ])('%s', (_label, text) => {
    expect(isFeedDocument(bytes(text))).toBe(false);
  });
});
